def _sort_key(label):
    # Arabic: treat the alef forms alike so أ / إ / آ / ا sort together.
    return label.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").casefold()


def options(gettext):
    """(common, everything) as lists of (stored English name, label in the current language)."""
    common = [(n, gettext(n)) for n in COMMON]
    everything = sorted(((n, gettext(n)) for _c, n in WORLD), key=lambda x: _sort_key(x[1]))
    return common, everything
